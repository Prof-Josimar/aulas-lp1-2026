package br.com.abc.introducao.arrays;

public class TemperaturasSemArray {
    public static void main(String[] args) {
        double tempSegunda = 30.5;
        double tempTerca = 28.0;
        double tempQuarta = 27.3;
        double tempQuinta = 29.8;
        double tempSexta = 31.2;
        double tempSabado = 32.0;
        double tempDomingo = 26.7;



        System.out.println("Segunda: " + tempSegunda);
        System.out.println("Terça: " + tempTerca);
        System.out.println("Quarta: " + tempQuarta);
        System.out.println("Quinta: " + tempQuinta);
        System.out.println("Sexta: " + tempSexta);
        System.out.println("Sábado: " + tempSabado);
        System.out.println("Domingo: " + tempDomingo);
    }
}
